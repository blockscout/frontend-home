import type { ScopeRule } from './select/scope';
import { createScopeRule } from './select/scope';

type CoverageMode = 'generate' | 'file' | 'off';

interface CliOptions {
  baseRef: string;
  diffSelected: boolean;
  maxCognitiveJsx: number;
  maxCognitiveBehavior: number;
  maxCrap: number | null;
  coverageMode: CoverageMode;
  coverageFile: string | undefined; // set only when coverageMode === 'file'
  verbose: boolean;
  focusPaths: Array<string>;
}

interface Run {
  readonly options: CliOptions;
  readonly isInScope: ScopeRule;
  readonly vitestConfig: string | undefined;
}

const USAGE = `Usage:
  code-complexity [--max-cognitive <n>] [--max-cognitive-jsx <n>]
                       [--max-cognitive-behavior <n>] [--max-crap <n>]
                       [--coverage-file <path> | --no-coverage] [--verbose]
      Full-repo mode (default): score every in-scope function.
      The readability gate is cognitive complexity, capped per function class:
      --max-cognitive-jsx for render bodies, --max-cognitive-behavior for handlers/hooks/utils;
      bare --max-cognitive sets both. --max-crap caps the CRAP score (cyclomatic × coverage).

  code-complexity <path...> [...]     Focused mode: score every function in the given files.

  code-complexity --changed[=<ref>] [--base <ref>] [...]
      Diff mode: gate only functions the diff touches vs the base ref.

  Coverage is generated by running vitest (scoped to the selection) unless --coverage-file supplies
  a prebuilt report (the CI path, skips vitest) or --no-coverage skips it (cognitive gate only).
  Vitest output is hidden by default; --verbose streams it live and adds the cyclomatic (CX) column.

  The scope, the caps, the base ref and the coverage source default to ${ CONFIG_FILE }
  in the working directory. With "coverage": false there, the cognitive gate alone is the default run.`;

// Cap values are positive integers; anything else is a typo worth failing on rather than silently
// defaulting.
function readCap(flag: string, raw: string): number {
  const value = Number(raw);
  if (!Number.isFinite(value) || value < 1) throw new Error(`Invalid value for ${ flag }: ${ raw }`);
  return value;
}

// The whole flag surface as data. Keeping it a lookup rather than an if/else chain is what leaves
// readability budget for the next flag.
const FLAGS: ReadonlyMap<string, FlagSpec<CliOptions>> = new Map<string, FlagSpec<CliOptions>>([
  [ '--verbose', { kind: 'switch', apply: (options) => {
    options.verbose = true;
  } } ],
  [ '--no-coverage', { kind: 'switch', apply: (options) => {
    options.coverageMode = 'off';
  } } ],
  [ '--coverage-file', { kind: 'value', apply: (options, value) => {
    options.coverageMode = 'file';
    options.coverageFile = value;
  } } ],
  [ '--changed', { kind: 'optional', apply: (options, value) => {
    options.diffSelected = true;
    if (value !== undefined) options.baseRef = value;
  } } ],
  [ '--base', { kind: 'value', apply: (options, value) => {
    options.diffSelected = true;
    options.baseRef = value;
  } } ],
  [ '--max-cognitive-jsx', { kind: 'value', apply: (options, value) => {
    options.maxCognitiveJsx = readCap('--max-cognitive-jsx', value);
  } } ],
  [ '--max-cognitive-behavior', { kind: 'value', apply: (options, value) => {
    options.maxCognitiveBehavior = readCap('--max-cognitive-behavior', value);
  } } ],
  // Bare --max-cognitive is a global that clamps both per-class caps.
  [ '--max-cognitive', { kind: 'value', apply: (options, value) => {
    const cap = readCap('--max-cognitive', value);
    options.maxCognitiveJsx = cap;
    options.maxCognitiveBehavior = cap;
  } } ],
  [ '--max-crap', { kind: 'value', apply: (options, value) => {
    options.maxCrap = readCap('--max-crap', value);
  } } ],
]);

export function parseArgs(argv: ReadonlyArray<string>, config: CodeComplexityConfig): CliOptions {
  const { options, rest } = parseFlags<CliOptions>(argv, FLAGS, {
    baseRef: config.baseRef,
    diffSelected: false,
    maxCognitiveJsx: config.maxCognitiveJsx,
    maxCognitiveBehavior: config.maxCognitiveBehavior,
    maxCrap: config.maxCrap,
    coverageMode: config.coverage.kind === 'off' ? 'off' : 'generate',
    coverageFile: undefined,
    verbose: false,
    focusPaths: [],
  }, { kind: 'reject', usage: USAGE });

  options.focusPaths = rest;
  if (options.coverageMode !== 'off' && options.maxCrap === null) {
    throw new Error(`A coverage run needs a CRAP cap: set maxCrap in ${ CONFIG_FILE } or pass --max-crap.`);
  }
  return options;
}

function normalizeDisplayPath(filePath: string): string {
  return filePath.replace(/\\/g, '/').replace(/^\.\//, '');
}

function readFile(filePath: string): string {
  return fs.readFileSync(filePath, 'utf8');
}

function thresholdsOf(options: CliOptions): Thresholds {
  return {
    maxCognitiveJsx: options.maxCognitiveJsx,
    maxCognitiveBehavior: options.maxCognitiveBehavior,
    maxCrap: options.maxCrap,
  };
}

// Skipping the run yields empty coverage, not null: null disables the CRAP gate, which would make a
// function's score depend on what else happened to be in the same selection.
function resolveCoverage(run: Run, request: CoverageRequest, anyNeedsCoverage: boolean): CoverageData | null {
  const { options, vitestConfig } = run;
  switch (options.coverageMode) {
    case 'off':
      return null;
    case 'file':
      // coverageFile is always set when the mode is 'file' (parseArgs reads its value).
      return readCoverageOrEmpty(options.coverageFile as string);
    case 'generate':
      return anyNeedsCoverage ? generateCoverage(request, { verbose: options.verbose, vitestConfig }) : parseCoverage('{}');
  }
}

function fileNeedsCoverage(file: string, source: string): boolean {
  return !fileContainsJsx(source, file) || hasCoLocatedSpec(file);
}

// Focused mode: score every function in the given files, no diff-scoping. Coverage comes from the
// files' transitive importers (`related`), matching what diff/full would give.
function runFocusedMode(run: Run): Array<ReportRow> {
  const { options } = run;
  const displayPaths = options.focusPaths.map(normalizeDisplayPath);
  const sources = new Map(displayPaths.map((displayPath) => [ displayPath, readFile(displayPath) ] as const));
  const needsCoverage = (displayPath: string): boolean => fileNeedsCoverage(displayPath, sources.get(displayPath) as string);

  // Generate coverage only for the files that need it, and only run vitest if there are any.
  const relatedPaths = displayPaths.filter(needsCoverage);
  const coverage = resolveCoverage(run, { mode: 'related', paths: relatedPaths }, relatedPaths.length > 0);

  return displayPaths.flatMap((displayPath) => buildFileRows(displayPath, sources.get(displayPath) as string, coverage, {
    thresholds: thresholdsOf(options),
    gate: () => true,
    // The one mode where a missing entry may just mean the hand-passed report predates the file.
    missingCoverageIsZero: options.coverageMode !== 'file',
  }));
}

// No per-file skip here: the repo always has files that need coverage, and generation runs the
// whole suite regardless.
function runFullMode(run: Run): Array<ReportRow> {
  const { options } = run;
  const files = getAllSourceFiles(process.cwd(), run.isInScope).filter((file) => fs.existsSync(file));
  if (files.length === 0) return [];
  const coverage = resolveCoverage(run, { mode: 'full' }, true);

  return files.flatMap((file) => {
    const source = readFile(file);
    return buildFileRows(file, source, coverage, {
      thresholds: thresholdsOf(options),
      gate: () => true,
      missingCoverageIsZero: true,
    });
  });
}

// Diff mode: gate only functions a changed line falls within, across in-scope changed files.
// Untouched functions in a changed file are listed but never flagged.
function runDiffMode(run: Run): Array<ReportRow> {
  const { options } = run;
  const baseCommit = resolveBaseCommit(options.baseRef, process.cwd());
  const changedFiles = getChangedFiles(baseCommit, process.cwd()).filter(run.isInScope).filter((file) => fs.existsSync(file));
  if (changedFiles.length === 0) return []; // nothing in scope: skip vitest entirely

  const sources = new Map(changedFiles.map((file) => [ file, readFile(file) ] as const));
  const needsCoverage = (file: string): boolean => fileNeedsCoverage(file, sources.get(file) as string);
  // A change that touches nothing needing coverage (e.g. only JSX components without specs) skips
  // the vitest run entirely.
  const coverage = resolveCoverage(run, { mode: 'changed', since: baseCommit }, changedFiles.some(needsCoverage));

  return changedFiles.flatMap((file) => {
    const changedRanges = getChangedLineRanges(baseCommit, file, process.cwd());
    return buildFileRows(file, sources.get(file) as string, coverage, {
      thresholds: thresholdsOf(options),
      gate: (fn) => rangesOverlap(changedRanges, fn.startLine, fn.endLine),
      // A changed behavior function missing from coverage is untested changed code -> 0%.
      missingCoverageIsZero: true,
    });
  });
}

function selectRows(run: Run): Array<ReportRow> {
  if (run.options.focusPaths.length > 0) return runFocusedMode(run);
  if (run.options.diffSelected) return runDiffMode(run);
  return runFullMode(run);
}

function emitGithubActionsOutput(rows: ReadonlyArray<ReportRow>, thresholds: Thresholds, table: string): void {
  for (const annotation of githubAnnotations(rows, thresholds)) console.log(annotation);
  const summaryPath = process.env.GITHUB_STEP_SUMMARY;
  if (summaryPath) fs.appendFileSync(summaryPath, `${ stepSummary(table) }\n`);
}

const HELP_FLAGS: ReadonlySet<string> = new Set([ '--help', '-h' ]);

// The working directory is the consumer's package root: the config file is read there, and every path in it
// and on the command line is relative to it.
export function main(argv: ReadonlyArray<string>): void {
  // Answered before the config is read, so that the usage text is there for a repository with no config yet.
  if (argv.some((arg) => HELP_FLAGS.has(arg))) {
    console.log(USAGE);
    return;
  }

  const config = loadConfig(process.cwd());
  const options = parseArgs(argv, config);
  const rows = selectRows({
    options,
    isInScope: createScopeRule(config.scope),
    vitestConfig: config.coverage.kind === 'vitest' ? config.coverage.vitestConfig : undefined,
  });

  if (rows.length === 0) {
    console.log('No functions to check.');
    return;
  }

  const table = formatTable(rows, thresholdsOf(options), options.verbose);
  console.log(table);

  if (process.env.GITHUB_ACTIONS) emitGithubActionsOutput(rows, thresholdsOf(options), table);

  if (rows.some(isOffender)) {
    process.exitCode = 1;
  }
}
